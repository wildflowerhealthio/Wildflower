// linter is in JSDoc-typed-JS mode where node:path's `dirname`/`resolve` come
// through as `any`; runtime correctness is exercised by `vp run build`.

// Build-time bundler for the injected sniffer script.
//
// Hermes (RN/Expo) strips function source after bytecode compilation,
// so `Function.prototype.toString()` returns `function () { [bytecode] }`
// at runtime on-device. The previous approach — calling `.toString()`
// at module load time on `installSniffer` — produced a syntactically-
// valid no-op when injected, leaving the sniffer silently uninstalled.
//
// This script bundles `src/sniffer-entry.ts` (which imports and invokes
// `installSniffer`) as a self-contained IIFE at build time, in Node where
// the source is fully available, and writes the resulting JS string into
// `src/sniffer-script.generated.ts`. `index.ts` then imports the string
// directly — no `.toString()` involved at runtime on any platform.
//
// Run via `vp run generate-sniffer-script`. The generated file is
// committed so Metro (resolving via the `source` export condition) sees
// it without needing a build step in the consuming app.

import { writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'

const here = dirname(fileURLToPath(import.meta.url))
const pkgRoot = resolve(here, '..')

const result = await build({
  entryPoints: [resolve(pkgRoot, 'src/sniffer-entry.ts')],
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: 'es2020',
  write: false,
  legalComments: 'none',
  minify: false,
})

const code = result.outputFiles[0].text.trim()

const generated = `// @generated by scripts/build-sniffer-script.mjs — do not edit by hand.
// Regenerate with \`vp run generate-sniffer-script\` after changing
// install-sniffer.ts. Committed so Metro can resolve via the \`source\`
// export condition without running a build step in the consuming app.

const snifferScriptSource: string = ${JSON.stringify(code)}

export { snifferScriptSource }
`

const outPath = resolve(pkgRoot, 'src/sniffer-script.generated.ts')
writeFileSync(outPath, generated, 'utf8')
// oxlint-disable-next-line no-console -- intentional build-step output
console.log(`Wrote ${outPath} (${code.length} chars)`)
