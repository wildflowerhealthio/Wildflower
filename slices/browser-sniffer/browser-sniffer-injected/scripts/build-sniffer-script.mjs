// oxlint-disable typescript/no-unsafe-assignment -- linter is in JSDoc-typed-JS mode where node:path's `dirname`/`resolve` and `fileURLToPath` come through as `any`; runtime correctness is exercised by `vp run build`.

// Build-time bundler for the injected sniffer script.
//
// Bundles `src/sniffer-entry.ts` (which imports and invokes
// `installSniffer`) as a self-contained IIFE and writes the resulting
// JS string into `src/sniffer-script.generated.ts`. `index.ts` then
// imports the string directly. The bundle is produced ahead of time so
// the injected page doesn't have to host a module loader or a runtime
// build step.
//
// Run via `vp run generate-sniffer-script`. The generated file is
// committed so consumers resolving via the `source` export condition
// see it without running a build step.

import { writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'

const here = dirname(fileURLToPath(import.meta.url))
const pkgRoot = resolve(here, '..')

const result = await build({
  entryPoints: [resolve(pkgRoot, 'src/sniffer-entry.ts')],
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: 'es2020',
  write: false,
  legalComments: 'none',
  minify: false,
})

const code = result.outputFiles[0].text.trim()

const generated = `// @generated by scripts/build-sniffer-script.mjs — do not edit by hand.
// Regenerate with \`vp run generate-sniffer-script\` after changing
// install-sniffer.ts. Committed so the \`source\` export condition
// resolves it without a build step in the consuming app.

const snifferScriptSource: string = ${JSON.stringify(code)}

export { snifferScriptSource }
`

const outPath = resolve(pkgRoot, 'src/sniffer-script.generated.ts')
writeFileSync(outPath, generated, 'utf8')
// oxlint-disable-next-line no-console -- intentional build-step output
console.log(`Wrote ${outPath} (${code.length} chars)`)
