/* oxlint-disable */
import { readdirSync, readFileSync, writeFileSync, statSync, mkdirSync } from 'node:fs'
import { join, relative, dirname, extname } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const DIST = join(__dirname, '../vendor/patient-browser/dist')
const OUT = join(__dirname, '../src/generated-patient-browser.ts')
const MOUNT = '/installed-apps/patient-browser'
const REBASE_EXTENSIONS = new Set(['.html'])
const REBASE_PREFIXES = ['/assets/', '/img/', '/config/']

const CONTENT_TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'application/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg',
  '.gif': 'image/gif',
  '.ico': 'image/x-icon',
  '.webp': 'image/webp',
  '.woff': 'font/woff',
  '.woff2': 'font/woff2',
  '.ttf': 'font/ttf',
  '.eot': 'application/vnd.ms-fontobject',
  '.otf': 'font/otf',
  '.txt': 'text/plain; charset=utf-8',
  '.map': 'application/json; charset=utf-8',
}

const SKIP_EXTENSIONS = new Set(['.map'])

const walk = (dir) => {
  const results = []
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry)
    const stat = statSync(full)
    if (stat.isDirectory()) {
      results.push(...walk(full))
    } else {
      results.push(full)
    }
  }
  return results
}

const files = walk(DIST)
const entries = []

const rebase = (text) => {
  let out = text
  for (const prefix of REBASE_PREFIXES) {
    out = out.split(prefix).join(`${MOUNT}${prefix}`)
  }
  return out
}

const DEFAULT_CONFIG_PATH = 'config/default.json5'
const DEFAULT_CONFIG_SOURCE = join(DIST, 'config/r4.json5')
const DEFAULT_CONFIG_SERVER_URL = '/fhir-r4'

for (const file of files) {
  const ext = extname(file).toLowerCase()
  if (SKIP_EXTENSIONS.has(ext)) continue
  const rel = relative(DIST, file).split('\\').join('/')
  if (rel === DEFAULT_CONFIG_PATH) continue
  const contentType = CONTENT_TYPES[ext] ?? 'application/octet-stream'
  let bytes = readFileSync(file)
  if (REBASE_EXTENSIONS.has(ext)) {
    bytes = Buffer.from(rebase(bytes.toString('utf8')), 'utf8')
  }
  const base64 = bytes.toString('base64')
  entries.push({ path: rel, contentType, base64, size: bytes.length })
}

const defaultConfigSource = readFileSync(DEFAULT_CONFIG_SOURCE, 'utf8')
const defaultConfigBody = defaultConfigSource.replace(
  /url:\s*"https:\/\/r4\.smarthealthit\.org"/,
  `url: ${JSON.stringify(DEFAULT_CONFIG_SERVER_URL)}`
)
const defaultConfigBytes = Buffer.from(defaultConfigBody, 'utf8')
entries.push({
  path: DEFAULT_CONFIG_PATH,
  contentType: 'application/json; charset=utf-8',
  base64: defaultConfigBytes.toString('base64'),
  size: defaultConfigBytes.length,
})

entries.sort((a, b) => a.path.localeCompare(b.path))

const body = entries
  .map(
    (e) =>
      `  ${JSON.stringify(e.path)}: { contentType: ${JSON.stringify(
        e.contentType
      )}, base64: ${JSON.stringify(e.base64)} },`
  )
  .join('\n')

const totalSize = entries.reduce((sum, e) => sum + e.size, 0)

const content = `/* eslint-disable */
// @ts-nocheck
// Generated by vendor-apps/scripts/generate-patient-browser.mjs — do not edit.
// Files: ${entries.length}, total raw bytes: ${totalSize}

export type AssetEntry = { readonly contentType: string; readonly base64: string }

export const assets: Readonly<Record<string, AssetEntry>> = {
${body}
}
`

mkdirSync(dirname(OUT), { recursive: true })
writeFileSync(OUT, content)

console.log(`Wrote ${entries.length} assets (${totalSize} bytes raw) to ${OUT}`)
